--    ไม่ใช่คนแจ้ง · คนจะปฏิเสธว่าไม่เกี่ยวต้องเป็น QA เท่านั้น"
--
-- ของเดิม: ช่อง `quality_related` ถูกเลือกที่ **ขั้น 4 โดยผู้ตรวจรับ = ฝ่ายที่แจ้ง**
--   เลือก "ไม่เกี่ยวกับคุณภาพ" = ใบข้าม QA ไปรอรับมอบทันที ⇒ ฝ่ายที่ถูกตรวจเปิดด่านของตัวเองได้
--   วัดจริง 14/09: 152 ใบเลือก "ไม่เกี่ยว" vs 96 ใบ "เกี่ยว" = **61% ของใบที่ผ่านขั้น 4 ไม่เคยผ่าน QA**
--   · ผังกระบวนการทางการของโรงงานไม่มีกล่อง "ข้าม QA" เลย — "หน่วยงานคุณภาพตรวจรับงานหลังซ่อม (QA)"
--     อยู่ในเส้นทางหลักทั้งสายช่าง PD และสาย MTN
--
-- ของใหม่ (โค้ดในคอมมิทเดียวกัน): ใบที่ผ่านขั้น 4 **จอดรอ QA เสมอ** · ตัวชี้ขาดเปลี่ยนจาก
--   `quality_related` → `qa_skipped_at` (ร่องรอยที่ QA กดเท่านั้น) ทั้งฝั่งเว็บและ edge 2 ตัว
--
-- ⚠️ ทำไมต้อง backfill — ถ้าไม่ทำ ใบเก่าจะถูก "ดึงกลับ" มารอ QA ทั้งที่ตัดสินไปแล้ว
--   วัดจริงก่อนแก้: status='checked' → 27 ใบ ระบุ "ไม่เกี่ยวกับคุณภาพ" แต่ **ไม่มี qa_skipped_at**
--   (ใบยุคก่อนมีคอลัมน์ร่องรอย) ⇒ กฎใหม่จะอ่านว่า "ยังไม่มีคำตัดสินของ QA" แล้วเด้งกลับไปขั้น 5
--   ⇒ stamp ให้ชัดว่า "ตัดสินด้วยกฎเดิม" — ไม่ใช่การโกหกว่า QA ตรวจ (ไม่แตะ qa_at/qa_result/qa_sign)
--   ไม่แตะใบที่ QA ตรวจจริงแล้ว และไม่แตะใบที่ระบุ "เกี่ยวกับคุณภาพ" (25 ใบ — รอ QA อยู่แล้ว ถูกต้องแล้ว)
-- ══════════════════════════════════════════════════════════════════════════

update public.mtn_orders
set qa_skipped_at  = coalesce(qa_skipped_at, check_at, updated_at, now()),
    qa_skipped_by  = coalesce(nullif(qa_skipped_by, ''), nullif(checker_name, ''), '(ระบบ — ใบก่อนเปลี่ยนกฎ)'),
    qa_skip_reason = coalesce(nullif(qa_skip_reason, ''),
      'ขั้น 4 ระบุว่าไม่เกี่ยวกับคุณภาพ (ตัดสินด้วยกฎเดิมก่อน 14/09/2026 ที่ผู้ตรวจรับเลือกเองได้) '
      || '— ตั้งแต่ 14/09/2026 เฉพาะ QA เท่านั้นที่ระบุได้'),
    updated_at     = now()
where status = 'checked'
  and qa_skipped_at is null
  and btrim(coalesce(quality_related, '')) = 'ไม่เกี่ยวกับคุณภาพ';

