-- สิ่งที่ผิดในแนวทางเดิม (ไม่ใช่แค่ต้นทุน — แต่ผิดเรื่องดีไซน์):
--   ย้าย "ทุกเหตุการณ์" จากห้องแชทมาเป็นแจ้งเตือนรายตัว = เอาของที่ห้องแชทรับไหว
--   (149 DT/วัน ไหลผ่านตา) มายัดใส่กระดิ่งส่วนตัวทีละใบ ⇒ คนอ่านไม่ไหวก็เลิกอ่านทั้งกระดิ่ง
--   **แจ้งเตือนที่ไม่มีใครอ่าน แย่กว่าไม่มีแจ้งเตือน** (บทเรียนเดียวกับคิว 4M auto 323 ใบ)
--
-- ต้นทุนที่วัดได้ (เพื่อบันทึกไว้ ไม่ให้ session หน้าประเมินผิดซ้ำ):
--   1 แถวใน `notifications` = trigger `fn_notify_push` ยิง pg_net → `send-push` **1 invocation ต่อแถว**
--   (ยิงแม้ user ไม่มี push subscription เลย) + คิวรี `push_subscriptions` 1 ครั้ง
--   ⇒ +2,000 แถว/วัน = +2,000 invocation/วัน · egress เองน้อย (~2-4 MB/วัน · payload ~1 KB)
--   **ตัวที่แพงจริงคือ invocation + แถวสะสม + คนเลิกอ่าน ไม่ใช่ egress** (egress ตัวใหญ่คือ poll/รูป)
--
-- ทิศทางที่ตกลงใหม่ (ยังไม่ลงมือ — รอ user เคาะรายการ "เร่งด่วน"):
--   · เรื่องเร่งด่วน = แจ้งทันทีรายตัว (เรียกช่าง MTN · DT ค้างเกินเกณฑ์ · PM แดง · สโตร์หยิบผิด)
--   · เรื่องที่เหลือ = **สรุปรายรอบ 1 ข้อความ** (ต่อกะ/ต่อวัน) ⇒ จาก N แถว เหลือ 1 แถวต่อคนต่อรอบ
