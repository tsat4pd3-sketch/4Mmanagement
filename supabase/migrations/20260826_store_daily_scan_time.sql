-- ⏰ เลื่อนเวลาสแกนเฝ้าระวังสโตร์ 08:30 → 07:50  (DR project · รันซ้ำได้)
--
-- 🔴 บั๊กที่แก้: เคส C (รอบส่งเลยเวลา) และ D (รับไม่ครบ) **ไม่มีทางเข้า Telegram ได้เลยตลอดกาล**
--
-- ทั้ง edge `store-daily-scan` และวิว `v_store_abnormal` คิด "วันงาน" ด้วยกฎเดียวกัน (ตัด 08:00)
-- ยิงตอน 08:30 น. ไทย ⇒ ชั่วโมง = 8 (ไม่ < 8) ⇒ work_date = **วันนี้** ที่เพิ่งเริ่มมา 30 นาที
--   และ now_frame_min = (8×60+30) − 480 = **30**
-- เคส C flag เมื่อ `now_frame_min > frameMin(รอบ) + dwell`
--   รอบที่ seed ไว้จริง 10:00 / 13:00 / 16:00 → frameMin = 120 / 300 / 480
--   ⇒ 30 > 120 ไม่มีทางเป็นจริง → **เคส C = 0 ทุกวัน** (ไม่ใช่ "ไม่มีปัญหา" แต่ "ยังไม่ถึงเวลาให้มีปัญหา")
-- เคส D อ่าน kanban_deliveries ของ "วันนี้" ตอน 30 นาทีแรกของวันงาน ⇒ แทบไม่มีแถว = 0 เช่นกัน
-- ⇒ ปัญหารอบส่งของเมื่อวานตกหายไปทั้งหมด — จอ /store-monitor เห็นครบ แต่ไม่มีใครถูกแจ้ง
--
-- ✅ แก้: ยิง 00:50 UTC = **07:50 น. ไทย** (ยังอยู่ใน "วันงานเมื่อวาน" เพราะชั่วโมง 7 < 8)
--   work_date = เมื่อวาน · now_frame_min = (7×60+50) − 480 + 1440 = **1430 จาก 1440**
--   ⇒ ครอบวันงานที่เพิ่งจบเกือบทั้งวัน — รอบส่งทุกกะ (รวมกะดึก) ถูกตรวจจริง
--
-- ผลข้างเคียงที่ตั้งใจ:
--   · ข้อความมาถึง 07:50 แทน 08:30 = สรุป "เมื่อวาน" อ่านก่อนเข้ากะ (เดิมสรุป "วันนี้" ที่ยังไม่มีอะไร)
--   · เคส A/B (สต๊อกเทียบ Min/Max) ไม่ผูกวันอยู่แล้ว → ความหมายเท่าเดิม
--   · เคส E (ใบสั่งซื้อค้าง) เทียบ `< work_date` → ใบที่ออกเมื่อวานยังไม่นับว่าค้าง
--     (ผ่อนลง 1 วัน — ตรงกับนิยาม "ค้างข้ามวันงาน" มากกว่าเดิม)
--   · รอบส่งที่กำหนดในช่วง 07:50–08:00 ของวันงานจะไม่ถูกตรวจ (10 นาทีสุดท้าย)
--     — เว้นระยะไว้กัน cron ดีเลย์แล้วหลุดข้ามไปวันใหม่ ซึ่งจะพากลับไปเป็นบั๊กเดิมทั้งดุ้น
--
-- ⚠️ ห้ามเลื่อนกลับไป ≥ 08:00 น. ไทย โดยไม่แก้วิธีคิดวันงานก่อน — เคส C/D จะตายเงียบอีกรอบ

select cron.unschedule('store-daily-scan')
 where exists (select 1 from cron.job where jobname = 'store-daily-scan');

