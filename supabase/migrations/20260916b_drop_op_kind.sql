-- ── ทำไมยัง "ถอดช่อง op_parent_mat ทิ้งทั้งอันไม่ได้" (วัดจริง 16/09) ────────────────────
-- ตั้งใจจะให้ระบบหา parent เองจาก BOM ของขั้น (component ที่เป็นสินค้ามีใบผลิตของตัวเอง)
-- แต่ **4 ขั้นที่พึ่ง parent อยู่จริง ยังไม่มี BOM เลยสักบรรทัด**:
--    `90031601`/`90031603` → `10100385` (2,231 ใบ) · `90031602`/`90031604` → `20065715` (468 ใบ)
--    `BENDING B222` → `20065107` (22 ใบ)
-- ถ้าเปลี่ยนไปอ่าน BOM วันนี้ = ขั้นพวกนี้เลิกถูกยุบ ⇒ **ยอด LASER/HDF เด้งเป็น 2 เท่าทันที**
-- (เคสเดียวกับที่เคย revert ฉุกเฉิน 15/09) ⇒ เก็บช่องไว้ก่อน ให้ BOM ของขั้นครบแล้วค่อยถอด
