select r.cost_center, r.note as sap_name,
       coalesce((select string_agg(name,' | ') from production_lines where cost_center = r.cost_center), '—') as line_ในระบบ,
       coalesce((select string_agg(name||'('||kind||')',' | ') from org_nodes where cost_center = r.cost_center), '—') as org_ในระบบ,
       round(r.dl_rate + r.dp_rate + r.idp_rate + r.oh_rate, 2) as rวม_บาทต่อชม
from public.cost_center_rates r
order by (select count(*) from production_lines where cost_center = r.cost_center) desc, r.cost_center;
