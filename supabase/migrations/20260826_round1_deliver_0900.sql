-- ⏰ รอบแรกเลื่อนเป็นส่ง 09:00  (DR · user 2026-08-26 "รอบแรก เปลี่ยนจาก 10:00 เป็น 9:00 ให้ที")
--
-- ⚠️ ตัดยอดเป็น **08:30 ไม่ใช่ 08:00** — ตั้ง 08:00 แล้วรอบแรกจะ "ตายสนิท"
--    หน้าต่างตัดยอดของรอบ = [cutoff รอบก่อนหน้า, cutoff รอบนี้) และรอบแรกเริ่มที่ต้นวันงาน 08:00
--    ⇒ cutoff 08:00 ทำให้หน้าต่างเป็น [08:00, 08:00) = ว่างเปล่า **ไม่มีใบผลิตใบไหนตกรอบนี้ได้เลย**
--    แล้วสโตร์จะเห็นรอบ 09:00 ว่างทุกวันโดยไม่รู้สาเหตุ (ล้มเหลวเงียบ)
--    วัดกับข้อมูลจริง 26/08 กะเช้า: ตัดยอด 08:30 → รอบ 1 ได้ 29 ใบ · รอบ 2 ได้ 99 ใบ
--
-- prep_minutes 60 → 30 ให้สอดคล้องกัน (ตัดยอด 08:30 → เริ่มจัดของ 08:30 → ส่ง 09:00)
--    ถ้าคง 60 ไว้ walkback จะเขียนว่า "เริ่มจัดของ 08:00" ซึ่งเป็นเวลา**ก่อน**ตัดยอด = อ่านแล้วขัดกันเอง

update public.kanban_delivery_rounds
   set cutoff_time   = time '08:30',
       delivery_time = time '09:00',
       prep_minutes  = 30
 where round_no = 1 and shift = 'day' and is_active;

