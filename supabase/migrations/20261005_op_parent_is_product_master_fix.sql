/* ── 2) เติม op_parent_mat ที่ว่าง (เฉพาะแถวที่ยังว่างจริง) ────────────────────────────
   ด่าน `exists (...)` = **ค่านี้ต้องเป็นค่าที่พี่น้อง OP ตัวอื่นผูกไว้แล้วจริง** — เป็นการพิสูจน์ว่า
   "ลอกมา ไม่ได้เดา" และยังรันซ้ำได้
   ⚠️ ห้ามเปลี่ยนด่านเป็น "parent ต้องมีใน dr_products" — `30051864` เป็นพาร์ทซื้อ (3xx)
      ที่**ไม่ได้ลงทะเบียนในทะเบียนสินค้า** (รอบแรก 05/10 ด่านนี้ทำให้ `173 M6` ไม่เข้า)
      ซึ่งไม่เป็นไรสำหรับ `collapseOps`: parent ที่ไม่เคยอยู่ในชุดข้อมูล = ยุบขั้นพี่น้องเป็นแถวเดียว
      (ซึ่งคือผลที่ต้องการ: M6 + M8 = ชิ้นเดียวกัน ห้ามบวกกัน) */
update public.dr_products d
   set op_parent_mat = v.parent
  from (values ('50031601',            '10100385'),
               ('50031602',            '20065715'),
               ('173 M6(มีเกลียว)',     '30051864'),
               ('E025 (M6 ไม่มีเกลียว)', '20058626'),
               ('E025 (M8 ไม่มีเกลียว)', '20058626')
       ) as v(mat_no, parent)
 where d.mat_no = v.mat_no
   and d.is_operation is true
   and d.op_parent_mat is null            -- 🔴 ห้ามทับค่าที่มีอยู่แล้ว
   and exists (select 1 from public.dr_products s
                where s.is_operation is true and s.op_parent_mat = v.parent);
