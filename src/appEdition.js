/** ชื่อที่ขึ้นบนหัว sidebar / splash */
export const EDITION_LABEL = 'ESM · Shopfloor';

/** หน้าแรกของรุ่นนี้ — RoleRoute เด้งมาที่นี่เมื่อเข้าหน้าที่ไม่มีสิทธิ์ด้วย */
export const EDITION_HOME = '/';

/**
 * รายชื่อหน้าที่เว็บรุ่นนี้ "มี" — `null` = มีครบทุกหน้า (รุ่นเต็ม)
 * 🔴 เป็น allowlist ของ **เว็บ** ไม่ใช่ของ **คน**
 */
export const EDITION_PAGES = null;

/** หน้านี้มีอยู่ในเว็บรุ่นนี้ไหม — รุ่นเต็มตอบจริงเสมอ (พฤติกรรมเดิมก่อนมีไฟล์นี้) */
export function inEdition(path) {
  if (!EDITION_PAGES) return true;
  const p = String(path || '').split(/[?#]/)[0];
  return EDITION_PAGES.includes(p);
}
