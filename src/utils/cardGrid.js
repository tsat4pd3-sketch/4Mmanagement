/* ══ cardGrid — ลิสต์การ์ด/แถวยาว วางเป็นหลายคอลัมน์อัตโนมัติตามความกว้างจริง ══════════════
   ที่มา (feedback user 2026-09-09): *"พื้นที่ตรงกลางว่างหลายส่วน เพราะเป็น 1 column/row
   คิดว่าแบ่งเป็น 2 column จะแปลกมั้ย"* → ไม่แปลก และตรงกับ `docs/UI-CONVENTIONS.md`
   §6.5 (จอ landscape ห้ามเหลือที่ว่างเยอะ) + §6.11 (เกณฑ์ "เหลือเกิน ~80px = ต้องจัดใหม่")

   วัดจากจอจริงของหัวหน้ากลุ่ม: แถวใบผลิตกว้าง ~1520px · เนื้อหาซ้ายจบ ~560px ·
   บล็อกยอดขวาเริ่ม ~1800px ⇒ **ช่องว่างกลาง ~1,240px** = 15 เท่าของเกณฑ์

   ทำไมเป็น CSS ล้วน ไม่ใช่ JS วัดจอ:
   - จอ TV/แท็บเล็ตหมุนจอ + sidebar ย่อ/กาง = ความกว้างเปลี่ยนบ่อย · auto-fit ปรับเองทันที
   - ไม่ต้องมี ResizeObserver เพิ่มในหน้าที่หนักอยู่แล้ว

   ⚠️ กติกาที่ต้องมาด้วยกันเสมอ (บทเรียน §6.11 · §7):
   - `alignItems:'start'` — ลูกสูงไม่เท่ากันห้ามถูกยืดเท่ากัน (การ์ดเตี้ยจะมีช่องดำยาวใต้ตัวหนังสือ)
   - `min(100%, Npx)` ไม่ใช่ `Npx` เฉยๆ — แผงพวกนี้ถูกวางในคอลัมน์แคบได้ (modal/2-column layout)
     ถ้าใช้ px ดิบ พอ container แคบกว่า N คอลัมน์จะล้นออกนอกกรอบแทนที่จะยุบเหลือ 1
   - ลูกทุกตัวต้องมี `minWidth: 0` เอง ไม่งั้นเนื้อหาที่ไม่ยอมหด (ตาราง/ชื่อยาว) ดันคอลัมน์ล้น

   หมายเหตุ: §6.11 ข้อ "จำนวนลูกต้องหารลงตัวกับคอลัมน์" ใช้กับ **แผงที่จำนวนคงที่**
   ลิสต์ที่ยาวไม่คงที่ (ใบผลิต/downtime/ของเสีย) แถวท้ายเหลือเศษเป็นเรื่องปกติ ไม่ใช่ช่องว่างที่ต้องแก้

   @param {number} minPx ความกว้างต่ำสุดต่อคอลัมน์ — เลือกจาก "บรรทัดที่ยาวที่สุดของแถวนั้น
     ยังอ่านครบโดยไม่ต้อง ellipsis" ไม่ใช่เลขกลมๆ (ดูค่าที่ใช้จริงในหน้าที่เรียก)
   @param {number} gap ระยะห่างระหว่างการ์ด (px)                                            */
export const cardGrid = (minPx = 520, gap = 6) => ({
  display: 'grid',
  gridTemplateColumns: `repeat(auto-fit, minmax(min(100%, ${minPx}px), 1fr))`,
  gap,
  alignItems: 'start',
});

export default cardGrid;
