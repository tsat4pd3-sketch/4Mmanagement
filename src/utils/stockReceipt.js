/** ชื่อคลังรับของซื้อ — ตรงกับที่ลูปสโตร์หัก (`deductStockForPick` ใช้ 'STORE')
 *  🔴 เปลี่ยนที่นี่ที่เดียว ห้ามพิมพ์ 'STORE' ซ้ำในหน้า */
export const RECEIPT_LINE = 'STORE';

const n = (v) => Number(v) || 0;
const txt = (v) => String(v ?? '').trim();

/**
 * สรุป "ใครรอของบ้าง" จากใบที่รับเข้าจริง — ไว้เขียนในหมายเหตุ ไม่ใช่ไว้เลือกปลายทาง
 * @param {Array} slips  ใบที่อัปเดตสำเร็จ (ต้องมี dest_line, qty)
 * @returns {string} เช่น "Assy GOR 318,000 · Line 60 38,000 · ไม่ระบุปลายทาง 500"
 */
export function destSummary(slips = []) {
  const m = new Map();
  slips.forEach(s => {
    const k = txt(s?.dest_line) || 'ไม่ระบุปลายทาง';
    m.set(k, (m.get(k) || 0) + n(s?.qty));
  });
  return [...m.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([k, q]) => `${k} ${q.toLocaleString()}`)
    .join(' · ');
}

/**
 * แถว ledger ของการรับของซื้อ — **1 แถวต่อ 1 พาร์ท ลงที่คลังเสมอ**
 *
 * เดิมแตกเป็น 1 แถวต่อ 1 ปลายทาง เพราะปลายทางคือ line_name · ตอนนี้ปลายทางเป็นแค่ข้อมูล
 * ⇒ ของก้อนเดียวที่เข้าคลังก้อนเดียว ควรเป็นแถวเดียว (แตกแถวโดยไม่มีคอลัมน์ผูกกลับใบ
 *   ไม่ได้เพิ่ม traceability เลย — ใบเองมี received_by/received_at เป็นหลักฐานอยู่แล้ว)
 *
 * @param {object} a
 * @param {string} a.matNo
 * @param {string} [a.partName]
 * @param {Array}  a.slips        ใบที่อัปเดตสำเร็จ ({ qty, dest_line, part_name, work_date })
 * @param {string} [a.supplier]
 * @param {string} a.workDate     วันงาน fallback เมื่อใบไม่มี
 * @param {string} [a.by]         ผู้บันทึก
 * @param {string} [a.storageLocation]  รหัสคลัง SAP ของ RECEIPT_LINE (null ได้ — ห้ามเดา)
 * @returns {Array} rows พร้อม insert (ว่าง = ไม่มีของให้รับ)
 */
export function buildReceiptRows({ matNo, partName, slips = [], supplier, workDate, by, storageLocation }) {
  const qty = slips.reduce((s, r) => s + n(r?.qty), 0);
  if (!(qty > 0)) return [];
  const where = destSummary(slips);
  return [{
    line_name: RECEIPT_LINE,
    mat_no: matNo,
    part_name: txt(partName) || txt(slips.find(s => txt(s?.part_name))?.part_name) || null,
    qty,
    type: 'issue',
    work_date: txt(slips.find(s => s?.work_date)?.work_date) || workDate,
    /* 🔴 หมายเหตุต้องบอก "ไลน์ไหนรอของ" ให้ครบ — สโตร์ใช้ตัดสินว่าจะจ่ายไปไหนก่อน
       และเป็นร่องรอยว่ายอดก้อนนี้มาจากใบซื้อกี่ใบ */
    note: `รับของซื้อเข้าคลัง · รวม ${slips.length} ใบ${supplier ? ` · ${supplier}` : ''}`
        + (where ? ` · ไลน์ที่รอของ: ${where}` : ''),
    created_by: txt(by) || 'สโตร์',
    ...(storageLocation ? { storage_location: storageLocation } : {}),
  }];
}
