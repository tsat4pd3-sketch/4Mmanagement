/**
 * @param  {...(any[]|null|undefined)} lists  ชุดแถว เรียง "เก่า/กว้าง → ใหม่/เฉพาะ" (ตัวหลังชนะ)
 * @returns {any[]} แถวละ 1 ตัวต่อ id · ลำดับภายในแต่ละชุดคงเดิม (ชุดแรกมาก่อน)
 */
export const mergeById = (...lists) => {
  const won = new Set();
  const out = [];
  // ไล่จากชุดท้ายสุดมาหน้า — ชุดหลังจอง id ไว้ก่อน แล้วชุดก่อนหน้าข้ามตัวที่ถูกจองแล้ว
  for (let i = lists.length - 1; i >= 0; i--) {
    const keep = [];
    for (const r of lists[i] || []) {
      const id = r?.id;
      if (id == null) { keep.push(r); continue; }   // ไม่มี id = ตัดสินไม่ได้ ห้ามทิ้ง
      const k = String(id);
      if (won.has(k)) continue;
      won.add(k);
      keep.push(r);
    }
    out.unshift(...keep);
  }
  return out;
};

/** แถวชุดเดียวที่อาจมีตัวซ้ำ (เช่นอ่านแบบแบ่งหน้าบนตารางที่คนยังกรอกอยู่) — ตัวแรกชนะ */
export const uniqueById = (rows) => mergeById(rows);
