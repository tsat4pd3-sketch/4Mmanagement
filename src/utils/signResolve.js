/** `uid → ลายเซ็นปัจจุบัน` จากรายชื่อโปรไฟล์ (`loadProfilesPeople()`) */
export function signMapOf(people) {
  const m = {};
  for (const p of Array.isArray(people) ? people : []) {
    if (p?.id && p.signature_url) m[p.id] = p.signature_url;
  }
  return m;
}

/**
 * ลายเซ็นที่ควรแสดงของช่องหนึ่ง
 * @param uid      คนที่เซ็นช่องนี้ (`checker_uid` / `reported_by_uid` / `tech_main_uid` …)
 * @param stored   ค่าที่เก็บไว้ในใบ (`checker_sign` …) — `null` ได้ถ้าช่องนั้นไม่เคยเก็บ
 * @param sigByUid ผลจาก `signMapOf()`
 * @returns URL รูป · `null` = ไม่มีลายเซ็นให้แสดง (จอ/ใบพิมพ์เว้นช่องไว้ให้เซ็นมือ)
 */
export function signUrlOf(uid, stored, sigByUid) {
  const live = uid && sigByUid ? sigByUid[uid] : null;
  return live || stored || null;
}
