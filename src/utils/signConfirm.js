/** จังหวะงานที่ถือเป็น "การอนุมัติ/เซ็นรับ" **ของใบ MO** — ชุดนี้ตรงกับ `stage` ใน mtnStepPerm.js
    (โมดูลอื่นไม่ต้องมีทะเบียน stage — เรียก `confirmSign()` ตรงจุดที่อนุมัติได้เลย) */
export const SIGN_STAGES = Object.freeze([
  'accept_work',      // ขั้นตรวจรับงานหลังซ่อม (ฝ่ายที่แจ้ง / หัวหน้าแผนกช่าง สำหรับใบ JIG-DIE)
  'qa',               // QA ตรวจ
  'handover',         // รับมอบงาน
  'close',            // ปิดใบ
  'mtn_head',         // หัวหน้าแผนกช่าง (ฟอร์ม MTN)
  'mtn_approve',      // ผจก.ช่าง (ฟอร์ม MTN)
  'cost_mgr_close',   // ผจก.ฝ่ายที่แจ้ง — ผู้ปิดใบ
]);

/** `true` = จังหวะนี้ต้องถามยืนยันก่อนเขียน */
export const needsSignConfirm = (stage) => SIGN_STAGES.includes(String(stage || ''));

const line = (label, v) => (v ? `${label}: ${v}` : null);

/**
 * ข้อความยืนยัน — **ต้องบอกครบ 3 อย่าง** (เซ็นอะไร · ใบไหน · ในนามใคร)
 * @param {string} what     สิ่งที่กำลังเซ็น เช่น 'ขั้น 4: ตรวจรับงานหลังซ่อม'
 * @param {string} orderNo  เลขใบ/เลขที่เอกสาร
 * @param {string} [docLabel] คำเรียกเอกสาร (default 'ใบ') เช่น 'ใบ 4M'
 * @param {string} actor    ชื่อคนที่กำลังกด (ชื่อที่จะไปปรากฏบนใบ)
 * @param {string} as       ช่องนี้เป็นของตำแหน่งไหน เช่น 'หัวหน้าแผนกผู้แจ้ง'
 * @param {string} [effect] ผลที่จะเกิดต่อจากนี้ (ใบเดินไปขั้นไหน / ปิดใบ)
 */
export function signConfirmText({ what, orderNo, actor, as, effect, docLabel = 'ใบ' } = {}) {
  return [
    `ยืนยันเซ็น — ${what || 'อนุมัติ'}`,
    '',
    line(docLabel, orderNo),
    line('เซ็นในนาม', [actor, as && `(${as})`].filter(Boolean).join(' ')),
    effect ? line('ผลที่จะเกิด', effect) : null,
    '',
    '⚠️ เซ็นแล้วแก้เองไม่ได้ — ต้องให้ผู้ถือสิทธิ์แก้ย้อนหลังมาปลดให้',
  ].filter(v => v !== null).join('\n');
}

/**
 * ถามยืนยันจริง — คืน `true` เมื่อผู้ใช้กดตกลง
 * แยกออกมาเพื่อให้ด่าน grep เจอจุดเดียว และเทสได้ (ส่ง `ask` เข้ามาแทน window.confirm)
 */
export function confirmSign(args = {}, ask = null) {
  const fn = ask || (typeof window !== 'undefined' ? window.confirm.bind(window) : null);
  if (!fn) return true;                  // ไม่มี window (เทส/SSR) = ไม่ขวาง
  return !!fn(signConfirmText(args));
}
