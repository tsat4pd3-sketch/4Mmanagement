export const KIOSK_PATHS = Object.freeze([
  '/tv',   // TvBoard — เปลือกเต็มจอของ <MtnAndonBoard> · เขียนแค่ query param ของตัวเอง
]);

/** หน้าที่เปิดอยู่เป็น "จอแขวน" หรือไม่ (ไม่สน trailing slash / ตัวพิมพ์) */
export function isKioskPath(pathname) {
  if (typeof pathname !== 'string' || !pathname) return false;
  const p = (pathname.split('?')[0].split('#')[0]).replace(/\/+$/, '').toLowerCase() || '/';
  return KIOSK_PATHS.includes(p);
}
