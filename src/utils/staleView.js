/* ══ 🔴 "ของบนจอเป็นของที่เลือกอยู่จริงไหม" — ด่านชั้น 2 ของ stale-response race (pure · 19/10) ═══
 *
 * กฎเหล็กการเขียน DB ข้อ 4 บอกให้ทุก effect ที่ `await` แล้ว `setState` มี guard (`alive`/request id)
 * ⇒ กันจอเพี้ยนได้ **แต่ไม่ได้กันการเขียน** · จอที่ประกอบ payload แบบ
 *     `{ id: <ที่โหลดมา>, line_name: <ที่เลือกอยู่> }`
 * ถ้าของที่โหลดมาเป็นของไลน์ก่อนหน้า = **เขียนทับแถวของไลน์อื่น** หรือชน PK แล้วเด้ง error ที่อ่านไม่รู้เรื่อง
 *
 * 🔴 เคสจริงที่ทำให้ต้องมี (QC audit ข้อ ④ · `/lpa`): คำถาม LPA ชั้น `common` ใช้ `question_id`
 *    **ร่วมกันทุกไลน์** ⇒ ใบร่างของไลน์ A ที่มาช้าทับจอที่เลือกไลน์ B แล้วกดบันทึก =
 *    **คำตอบของไลน์ A ไปลงเป็นของไลน์ B โดยไม่มี error** · LPA เป็นบันทึก audit ตามระบบคุณภาพ ⇒ แก้ย้อนไม่ได้
 *
 * วิธีใช้ (2 ชั้นคู่กัน — ชั้นเดียวไม่พอ):
 *   ① ใน loader: `const key = viewKey(line, shift, date)` ก่อนยิง → หลัง await เทียบกับ ref ของจอ ไม่ตรง = ทิ้ง
 *   ② ตอนกดบันทึก: เก็บคีย์ที่โหลดมาไว้ (state/ฟิลด์ในใบร่าง) แล้วเช็ค `isStale()` — จริง = **ห้ามเขียน**
 *      พร้อมขึ้นข้อความจาก `staleBlockText()` (ต้องบอกทางแก้ ไม่ใช่แค่ "ไม่สำเร็จ")
 *
 * 🔴 `loadedKey` ว่าง = **ยังไม่เคยโหลด ≠ ของไลน์อื่น** ⇒ ไม่ถือว่า stale
 *    (ไม่งั้นจอที่ยังไม่มีข้อมูล เช่นสร้างแผนเดือนใหม่ จะกดบันทึกไม่ได้เลย)
 */

/** ประกอบคีย์ของ "สิ่งที่จอกำลังดูอยู่" — `null`/`undefined` กลายเป็นค่าว่าง (ไม่ใช่ "null") */
export const viewKey = (...parts) => parts.map(p => (p === null || p === undefined ? '' : String(p))).join('|');

/** ของที่โหลดมา เป็นของคนละอย่างกับที่จอเลือกอยู่ไหม · ว่าง = ยังไม่โหลด = ไม่ stale */
export const isStale = (loadedKey, currentKey) => !!loadedKey && loadedKey !== currentKey;

/** ข้อความบนจอ — **ต้องบอกทางแก้** (ENGINEERING-PRINCIPLES: ห้ามขึ้นแค่ "บันทึกไม่สำเร็จ") */
export function staleBlockText({ what = 'ข้อมูลที่แสดงอยู่', unitWord = 'ไลน์/กะ/วันที่' } = {}) {
  return `${what}เป็นของ${unitWord}อื่น (ข้อมูลมาช้ากว่าการเปลี่ยนตัวเลือก)`
    + ` — เลือก${unitWord}ที่ต้องการอีกครั้งให้โหลดใหม่ก่อนบันทึก`;
}
