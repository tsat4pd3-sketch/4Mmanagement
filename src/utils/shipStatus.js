/** สถานะ "จบงานสำเร็จ" — ของถึงมือลูกค้าแล้ว (ห้ามเปลี่ยนค่านี้ ทั้งระบบผูกกับมัน) */
export const SHIPPED = 'shipped';

/** สถานะ "ปิดใบโดยไม่ได้ส่ง" — ลูกค้ายกเลิก / ใบผี / นำเข้าผิด */
export const CANCELLED = 'cancelled';

/** ปิดแล้ว = ไม่ต้องทำอะไรต่อ ไม่นับเป็นงานค้าง ไม่ขึ้นแดง */
export const CLOSED_STATUSES = [SHIPPED, CANCELLED];

/** ต่อท้ายคิวรี supabase: เอาเฉพาะใบที่ยังเป็นงานค้างจริง
 *  ใช้แทน `.neq('status','shipped')` ทุกจุด — เพิ่มสถานะปิดใหม่ในอนาคตก็แก้ที่นี่ที่เดียว */
export const openOnly = (q) => q.not('status', 'in', `("${CLOSED_STATUSES.join('","')}")`);

/** ฝั่ง JS (กรองจาก array ที่โหลดมาแล้ว) */
export const isClosedOrder = (o) => CLOSED_STATUSES.includes(o?.status);
export const isOpenOrder   = (o) => !isClosedOrder(o);
export const isCancelled   = (o) => o?.status === CANCELLED;
export const isShipped     = (o) => o?.status === SHIPPED;
