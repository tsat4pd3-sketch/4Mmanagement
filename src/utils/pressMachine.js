/* ═══ "เครื่องนี้เป็นเครื่องปั๊มไหม" — ตัดสินว่าจะโชว์ช่อง shut height ในฟอร์มเครื่องจักรหรือไม่ (2026-10-19) ═══
   user 19/10: *"เครื่องจักรก็ไม่มี shut height รึป่าว"* (ภาพ: ฟอร์ม RB-95 หุ่นยนต์ ABB มีช่อง shut height)
   ⇒ shut height = ช่วงที่ **เครื่องปั๊ม** รับแม่พิมพ์ได้ (คู่กับ die height ของแม่พิมพ์ · `utils/pressSetup.js`)
     หุ่นยนต์/เครื่องเชื่อม/คอนเวเยอร์ไม่มีค่านี้ — โชว์ทุกเครื่อง = ชวนกรอกมั่ว

   ทะเบียน `machine_types` ไม่มีแถวชื่อ "Press" (19/10) — ประเภทของเครื่องปั๊มคือ "Metal Forming"
   ⇒ ตัดสินจากชื่อประเภทด้วยคำที่ชี้ชัดเท่านั้น · 🔴 **ไม่ใช่ = ซ่อนช่อง ไม่ใช่ล้างค่า**:
     · เครื่องที่ **มีค่ากรอกไว้แล้ว** โชว์เสมอ (ห้ามซ่อนข้อมูลที่มีอยู่)
     · ฟอร์มมีปุ่ม "เครื่องนี้เป็นเครื่องปั๊ม — กรอก shut height" ให้เปิดเองได้ (ประเภทตั้งชื่ออื่น/ยังไม่ตั้ง)
   ═══════════════════════════════════════════════════════════════════════════════════════════════ */
export const PRESS_TYPE_RE = /press|เพรส|ปั๊ม|stamping|metal\s*forming/i;

/** ชื่อประเภทนี้คือเครื่องปั๊มไหม */
export const isPressType = (label) => PRESS_TYPE_RE.test(String(label || ''));

/** ควรโชว์ช่อง shut height ไหม — ประเภทเป็นเครื่องปั๊ม หรือ มีค่ากรอกไว้แล้ว */
export function showsShutHeight({ typeLabel, min, max } = {}) {
  const has = (v) => v != null && String(v).trim() !== '';
  return isPressType(typeLabel) || has(min) || has(max);
}
