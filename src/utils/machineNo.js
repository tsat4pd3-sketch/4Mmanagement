/** คีย์ของ "สายไลน์" จากรายชื่อไลน์ในครอบครัว (`lineFamilyOf()` · utils/lineHierarchy)
 *  เรียงก่อนต่อ ⇒ สมาชิกทุกตัวของสายเดียวกันได้คีย์เดียวกันเสมอ · ว่าง = ไม่รู้สาย */
export function lineFamilyKey(famNames) {
  const a = (Array.isArray(famNames) ? famNames : [])
    .map(n => machineKey(n)).filter(Boolean).sort();
  return a.length ? a.join('|') : '';
}

/**
 * ผูกคีย์เครื่องเข้ากับ "สายไลน์" — ใช้กับ **เครื่องที่ยังไม่อยู่ในทะเบียน** เท่านั้น
 *
 * 🔴 **รับคีย์ที่ normalize มาแล้ว** ไม่ normalize ซ้ำ — แต่ละจอมีตัว normalize ของตัวเอง
 *    (`normEquipKey` ใน mtnMetrics เก็บศูนย์นำหน้า · `machineKey` ตัดทิ้ง) ถ้าไฟล์นี้บังคับตัวใดตัวหนึ่ง
 *    คีย์ของเครื่องที่ขึ้นทะเบียนแล้วจะเปลี่ยนยกระบบ = ประวัติ MTBF/พาเรโตขยับโดยไม่มีใครสั่ง
 * @param {string} normKey คีย์เครื่องที่ normalize แล้ว
 * @param {string} famKey  คีย์สายไลน์จาก `lineFamilyKey()` · ว่าง = ไม่รู้สาย ⇒ คืนคีย์เดิม (ห้ามเดา)
 */
export const scopeKeyByFamily = (normKey, famKey) =>
  (normKey && famKey ? `${famKey}\u2237${normKey}` : (normKey || ''));

/**
 * สร้างตัวแมป "คีย์ → เลขเครื่องในทะเบียน" จากทะเบียนเครื่องจักร
 * 🔴 คีย์ที่ชี้ไปได้ **มากกว่า 1 เครื่อง** ถูกทิ้ง — กำกวม = ไม่แตะดีกว่าแก้ผิด
 * @param {Array<{machine_no:string}|string>} machines
 */
export function buildMachineKeyMap(machines = []) {
  const byKey = new Map();
  for (const m of (Array.isArray(machines) ? machines : [])) {
    const no = String((typeof m === 'string' ? m : m?.machine_no) ?? '').trim();
    if (!no) continue;
    const k = machineKey(no);
    if (!k) continue;
    if (!byKey.has(k)) byKey.set(k, new Set());
    byKey.get(k).add(no);
  }
  const out = new Map();
  for (const [k, set] of byKey) if (set.size === 1) out.set(k, [...set][0]);
  return out;
}

/**
 * ข้อความที่พิมพ์มา → เลขเครื่องตามทะเบียน (ถ้าเป็นแค่เรื่องรูปแบบ)
 * @returns {string|null} null = ไม่ใช่เครื่องในทะเบียน (ปล่อยค่าเดิมไว้ ห้ามดัด)
 */
export function snapMachineNo(text, keyMap) {
  const t = String(text ?? '').trim();
  if (!t || !(keyMap instanceof Map)) return null;
  const hit = keyMap.get(machineKey(t));
  return hit && hit !== t ? hit : null;
}

/**
 * 🔎 รูปแบบ `ilike` ที่ "ครอบ" ทุกสะกดของเครื่องนี้ — ใช้กรองหยาบฝั่ง server เท่านั้น (2026-10-19)
 * `SW-10` → `%SW%10%` จับ `SW10` · `sw 10` · `SW-010` ได้ แต่ก็จับ `SW-100` ด้วย
 * ⇒ 🔴 **ผลที่ได้ต้องกรองซ้ำด้วย `machineKey()` เสมอ** (ด่านชั้นสองแบบเดียวกับ MachineRepairHistory)
 * คีย์มีแต่ A-Z/0-9/ไทย ⇒ ไม่มี `% _ , ( )` หลุดไปทำ filter ของ PostgREST เพี้ยน
 * @returns {string|null} null = ไม่มีอะไรให้ค้น
 */
export function machineNoLikePattern(s) {
  const k = machineKey(s);
  if (!k) return null;
  const runs = k.match(/[0-9]+|[^0-9]+/g) || [];
  return `%${runs.join('%')}%`;
}
