/* ผังแป้นเกษมณี (Kedmanee) — อักษรไทย → ตัวที่อยู่ "ปุ่มเดียวกัน" ฝั่งอังกฤษ
   ครอบเฉพาะแถวตัวเลข + ตัวอักษรที่โผล่ในรหัสจริง (เลขใบผลิต/MAT เป็นตัวเลขล้วน
   แต่บางทะเบียนมีตัวอักษรปน) · ไม่ครอบทั้งแป้นโดยตั้งใจ — ยิ่งครอบกว้าง ยิ่งแปลงมั่ว */
const TH2EN = {
  // แถวตัวเลข
  'ๅ': '1', '/': '2', '-': '3', 'ภ': '4', 'ถ': '5', 'ุ': '6', 'ึ': '7', 'ค': '8', 'ต': '9', 'จ': '0',
  // แถวบน
  'ๆ': 'q', 'ไ': 'w', 'ำ': 'e', 'พ': 'r', 'ะ': 't', 'ั': 'y', 'ี': 'u', 'ร': 'i', 'น': 'o', 'ย': 'p',
  // แถวกลาง
  'ฟ': 'a', 'ห': 's', 'ก': 'd', 'ด': 'f', 'เ': 'g', '้': 'h', '่': 'j', 'า': 'k', 'ส': 'l',
  // แถวล่าง
  'ผ': 'z', 'ป': 'x', 'แ': 'c', 'อ': 'v', 'ิ': 'b', 'ื': 'n', 'ท': 'm',
};

/** มีอักษรไทยอยู่ในสตริงไหม (ช่วง Unicode ภาษาไทย) */
export const hasThai = (s) => /[฀-๿]/.test(String(s ?? ''));

/** รหัสที่ระบบยอมรับได้: ตัวเลข/อังกฤษ/ขีด/ขีดล่าง เท่านั้น (ต้องมีอย่างน้อย 1 ตัว) */
const isCleanCode = (s) => /^[A-Za-z0-9][A-Za-z0-9_-]*$/.test(s);

/**
 * แปลงข้อความที่พิมพ์ตอนแป้นค้างภาษาไทย → รหัสจริง
 * @returns { value, fixed }  · `fixed` = แปลงให้จริงหรือเปล่า (ใช้ตัดสินว่าจะเตือนผู้ใช้ไหม)
 *   แกะไม่ออก/ไม่ได้เป็นภาษาไทย = คืนค่าเดิม `fixed:false` — ปลายทางค่อยปฏิเสธพร้อมเหตุผล
 */
export function fixThaiLayout(raw) {
  const s = String(raw ?? '').trim();
  if (!s || !hasThai(s)) return { value: s, fixed: false };
  let out = '';
  for (const ch of s) {
    const en = TH2EN[ch];
    if (en === undefined) return { value: s, fixed: false };   // มีตัวที่ไม่อยู่ในผัง = ไม่ใช่เคสแป้นค้าง
    out += en;
  }
  return isCleanCode(out) ? { value: out, fixed: true } : { value: s, fixed: false };
}

/** ข้อความเตือนมาตรฐาน — ให้ทุกจอพูดเหมือนกัน (คนหน้างานเห็นคำเดียวกันทุกที่) */
export const thaiLayoutNote = (before, after) =>
  `⌨️ แป้นพิมพ์ค้างอยู่ภาษาไทย — แปลง "${before}" ให้เป็น "${after}" แล้ว · สลับแป้นเป็นอังกฤษก่อนยิงใบถัดไป`;
