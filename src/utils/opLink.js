import { matClassOf } from './matPrefix.js';

const norm = (s) => (s ?? '').toString().trim().toUpperCase();

/**
 * ขั้นนี้ "เสี่ยงนับซ้ำ" อยู่ไหม — ใช้คุมแถบเตือน 🔩 (คืน null = ไม่ต้องเตือน)
 *
 * เตือนเมื่อ: เป็น OP · ยังไม่ผูก `op_parent_mat` · แต่ในสูตรของมันมีของที่ "มีใบผลิตของตัวเอง"
 * ⇒ ของชิ้นนั้นถูกนับไปแล้วรอบหนึ่ง พอขั้นนี้นับอีก = ชิ้นเดียวกันนับ 2 รอบ
 *
 * @param {object}   item          { is_operation, op_parent_mat, mat_no }
 * @param {string[]} ownBomMats    mat ของ component ในสูตรของขั้นนี้ ([] = ยังไม่ผูกสูตร → เงียบ)
 * @param {Function} isCountedMat  (mat) => boolean — mat นี้มีใบผลิตของตัวเองไหม (เป็นสินค้าในระบบ)
 * @returns {{candidates:string[]}|null}  candidates = ตัวที่ควรเลือกเป็น parent (ปกติมีตัวเดียว)
 */
export function opDoubleCountRisk(item, ownBomMats = [], isCountedMat = () => false) {
  if (!item?.is_operation) return null;
  if (norm(item.op_parent_mat)) return null;          // ผูกแล้ว = ระบบยุบให้อยู่แล้ว
  const candidates = [...new Set((ownBomMats || []).map(m => (m ?? '').toString().trim()).filter(Boolean))]
    .filter(m => isCountedMat(m));
  return candidates.length ? { candidates } : null;   // ไม่มีของที่ถูกนับอยู่แล้ว = ไม่มีอะไรให้ซ้ำ
}

/**
 * คำเตือนความไม่สอดคล้องของขั้น 1 ตัว — คืน [] = ไม่มีปัญหา
 *
 * 🔴 กฎที่ใช้ตัดสิน (user ยืนยัน 2026-10-05):
 *    *"ปลายทางจะไปต้องไปจบที่พาร์ทจริงที่มี mat sap ส่วนใหญ่ ยกเว้นจะเป็น sub ของ sub
 *      อีกทีก่อนจะกลายเป็นพาร์ท 2xxx หรือ 1xxx"*
 *    ⇒ ไล่ตามสายไปเรื่อยๆ (ขั้น → ขั้น → … ) **ปลายสายต้องเป็น FG (1xxx) หรือ Child ผลิตเอง (2xxx)**
 *    เพราะมีแต่ 2 ชนิดนี้ที่ "มีใบผลิตของตัวเอง" ให้ `collapseOps()` ยุบยอดเข้าไปได้จริง
 *    ปลายทางเป็นของซื้อนอก (3xxx) / วัตถุดิบ (5xxx) = **ผูกไปก็ไม่มีผล** ยอดขั้นยังถูกนับเหมือนเดิม
 *
 * ⚠️ **ห้ามเตือนเรื่องทิศทาง** (parent อยู่ในสูตรของขั้น หรือขั้นอยู่ในสูตรของ parent) —
 *    วัดจริง 05/10: ข้อมูลใช้ **ทั้งสองทิศ** และถูกทั้งคู่
 *      · ขั้นขับนัท 8 ตัว (`E025`/`D04`/`127`/`290`…) → parent = **ของที่รับเข้ามา** (อยู่ในสูตรตัวเอง 8/8)
 *      · ขั้น STEP 1 / เลเซอร์ / ดัด 16 ตัว → parent = **ของที่ทำเสร็จแล้วกลายเป็น** (ยังไม่มีสูตร)
 *    เคยมีกฎ "parent ต้องอยู่ในสูตรของขั้นนี้" อยู่ตรงนี้ — **ถอดออกแล้ว** เพราะพอ BOM ของ 16 ตัวนั้น
 *    กรอกครบเมื่อไหร่ จอจะขึ้นแดงใส่ขั้นที่ถูกต้องทันที (คำถามที่ระบบต้องการคำตอบไม่ใช่ "ก่อน/หลัง"
 *    แต่คือ "ยอดนี้ไปซ้ำกับใบผลิตของพาร์ทจริงตัวไหน")
 *
 * @param {object} item  { is_operation, op_parent_mat }
 * @param {object} opts
 *   @param {Function} [opts.parentOf]  (mat) => op_parent_mat ของ mat นั้นถ้ามันเป็นขั้นด้วย ·
 *                                      คืน undefined/null = ไม่ใช่ขั้น (= ปลายสาย) · ไม่ส่ง = ไม่ไล่ต่อ
 * @returns {Array<{level:string,text:string}>}
 */
export function opLinkIssues(item, opts = {}) {
  if (!item?.is_operation) return [];
  const parent = norm(item.op_parent_mat);
  if (!parent) return [];                              // ว่างได้เสมอ — ไม่ใช่ "กรอกไม่เสร็จ"
  const parentOf = typeof opts.parentOf === 'function' ? opts.parentOf : () => null;

  /* ไล่ตามสาย: ขั้น → ขั้น → … จนเจอตัวที่ไม่ใช่ขั้น (ปลายสาย) · กันวนลูปด้วย seen */
  const seen = new Set([norm(item.mat_no)]);
  let cur = parent;
  for (let hop = 0; hop < 12; hop++) {
    if (seen.has(cur)) {
      return [{ level: 'warn', text: `สายของขั้นนี้วนกลับมาที่ ${cur} — ยอดจะยุบไม่ได้ ต้องแก้ให้ปลายทางเป็นพาร์ทจริง` }];
    }
    seen.add(cur);
    const next = norm(parentOf(cur));
    if (!next) break;                                  // ไม่ใช่ขั้น = ถึงปลายสายแล้ว
    cur = next;
  }

  const cls = matClassOf(cur);
  if (!cls) {
    return [{ level: 'warn', text:
      `ปลายทางของสายคือ "${cur}" ซึ่งไม่ใช่เลข MAT SAP 8 หลัก — ควรจบที่พาร์ทจริง (1xxx FG หรือ 2xxx ผลิตเอง)` }];
  }
  if (cls.key === 'fg' || cls.key === 'child') return [];
  return [{ level: 'warn', text:
    `ปลายทางของสายคือ ${cur} (${cls.label}) ซึ่งไม่มีใบผลิตของตัวเอง ⇒ ผูกไว้ก็ไม่ช่วยยุบยอด — `
    + 'ควรชี้ไปที่พาร์ทจริงที่มีใบผลิต (1xxx FG / 2xxx ผลิตเอง) หรือปล่อยว่าง' }];
}
