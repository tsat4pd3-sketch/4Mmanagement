/* ═══ 🔩 ขั้นตอน (OP) — "ยอดของขั้นนี้ไปซ้ำกับใบผลิตของใคร" (pure · มีเทส) ═══════════════
   คำสั่ง user 2026-09-16:
     "ที่จริงเรื่องพาร์ทที่ยิงนัทเข้าไป มันก็มองเป็นพาร์ทตัวใหม่ได้ปะ เพราะของเดิมไม่มีนัท
      ตัวใหม่มีนัท **ไม่อยากให้มีหลายแบบ**"

   ⇒ ยุบเหลือ **แนวคิดเดียว**: ทุกขั้นคือ "ของชิ้นใหม่" (Part A + นัท ≠ Part A) — ถูกต้องตามของจริง
     เคยลองแยก `op_kind` = sequence/assembly แล้ว **ถอดออกวันเดียวกัน** (20260916b) เพราะเป็นการ
     ถามคำถามผิด · คำถามเดียวที่ระบบต้องการคำตอบคือ:

        **"ยอดผลิตของขั้นนี้ ไปซ้ำกับใบผลิตของของชิ้นไหน"**  → `op_parent_mat` · **ว่างได้เสมอ**

     ว่าง = ไม่มีใครให้ซ้ำ (ของที่ประกอบมาไม่มีใบผลิตของตัวเอง) — ไม่ใช่ "ยังกรอกไม่เสร็จ"

   🔴 ทำไม "ว่าง" ถึงไม่กำกวมอีกต่อไปโดยไม่ต้องมีคอลัมน์บอกชนิด:
      แถบเตือนเลิกดูที่ "ช่องว่าง" แล้วไปดู **อาการจริง** แทน — ขั้นที่ยังไม่ผูก parent
      **แต่ในสูตร (BOM) ของมันมี component ที่เป็นสินค้าซึ่งมีใบผลิตของตัวเอง** = เสี่ยงนับซ้ำจริง
      วัดจริง 16/09: เข้าข่ายแค่ `E025 (M6/M8 ไม่มีเกลียว)` (กิน `20058626`) · `173 M6` กับ
      `FENDER`/291+088 ไม่เข้าข่าย ⇒ **เงียบ ไม่ต้องให้ใครมากรอกอะไร** (นี่คือสิ่งที่ user ต้องการ)

   ⚠️ ยังถอดช่อง `op_parent_mat` ทิ้งไม่ได้ (วัดจริง 16/09) — ตั้งใจให้ระบบหา parent เองจาก BOM
      แต่ **4 ขั้นที่พึ่ง parent อยู่จริงยังไม่มี BOM เลยสักบรรทัด** (`90031601`-`04` → 10100385/20065715
      · `BENDING B222` → 20065107) ⇒ เปลี่ยนไปอ่าน BOM วันนี้ = ยอด LASER/HDF เด้ง 2 เท่าทันที
      (เคสเดียวกับที่ revert ฉุกเฉิน 15/09) · ให้ BOM ของขั้นครบก่อน แล้วค่อยถอดช่องนี้
   ═══════════════════════════════════════════════════════════════════════════════════════ */

const norm = (s) => (s ?? '').toString().trim().toUpperCase();

/**
 * ขั้นนี้ "เสี่ยงนับซ้ำ" อยู่ไหม — ใช้คุมแถบเตือน 🔩 (คืน null = ไม่ต้องเตือน)
 *
 * เตือนเมื่อ: เป็น OP · ยังไม่ผูก `op_parent_mat` · แต่ในสูตรของมันมีของที่ "มีใบผลิตของตัวเอง"
 * ⇒ ของชิ้นนั้นถูกนับไปแล้วรอบหนึ่ง พอขั้นนี้นับอีก = ชิ้นเดียวกันนับ 2 รอบ
 *
 * @param {object}   item          { is_operation, op_parent_mat, mat_no }
 * @param {string[]} ownBomMats    mat ของ component ในสูตรของขั้นนี้ ([] = ยังไม่ผูกสูตร → เงียบ)
 * @param {Function} isCountedMat  (mat) => boolean — mat นี้มีใบผลิตของตัวเองไหม (เป็นสินค้าในระบบ)
 * @returns {{candidates:string[]}|null}  candidates = ตัวที่ควรเลือกเป็น parent (ปกติมีตัวเดียว)
 */
export function opDoubleCountRisk(item, ownBomMats = [], isCountedMat = () => false) {
  if (!item?.is_operation) return null;
  if (norm(item.op_parent_mat)) return null;          // ผูกแล้ว = ระบบยุบให้อยู่แล้ว
  const candidates = [...new Set((ownBomMats || []).map(m => (m ?? '').toString().trim()).filter(Boolean))]
    .filter(m => isCountedMat(m));
  return candidates.length ? { candidates } : null;   // ไม่มีของที่ถูกนับอยู่แล้ว = ไม่มีอะไรให้ซ้ำ
}

/**
 * คำเตือนความไม่สอดคล้องของขั้น 1 ตัว — คืน [] = ไม่มีปัญหา
 * ⚠️ **ห้ามเตือนเรื่อง "parent เป็น component ของตัวเอง"** — นั่นคือเรื่อง**ปกติ**
 *    (ขั้นกิน Part A เข้าไปแล้วคาย Part A ที่มีนัท · 8/18 ขั้นในฐานจริงเป็นแบบนี้)
 *    เคยเกือบใส่กฎนี้ไปแล้วรอบหนึ่ง — จะขึ้นแดงใส่ขั้นที่ถูกต้องเกือบครึ่ง
 */
export function opLinkIssues(item, ownBomMats = []) {
  if (!item?.is_operation) return [];
  const parent = norm(item.op_parent_mat);
  if (!parent || !ownBomMats.length) return [];
  if (ownBomMats.some(m => norm(m) === parent)) return [];
  /* ผูก parent ไว้ แต่สูตรไม่ได้กินของตัวนั้นเข้าไป = ขั้นอ้างว่าทำต่อจากของที่มันไม่ได้รับมา
     เตือนอย่างเดียว ไม่ฟันธง (สูตรอาจกรอกไม่ครบ) */
  return [{ level: 'warn', text:
    `ผูกไว้ว่าทำต่อจาก ${item.op_parent_mat} แต่ของชิ้นนั้นไม่อยู่ในสูตรของขั้นนี้ — ปกติต้องกินเข้าไปด้วย` }];
}
