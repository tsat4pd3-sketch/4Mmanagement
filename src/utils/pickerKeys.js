/** ไม่มีแถวไหนถูกเล็ง — `rows[NO_ROW]` ต้องเป็น undefined เสมอ (Enter จึงไม่ทำอะไร) */
export const NO_ROW = -1;

/**
 * แถวที่ถูกเล็งตอนลิสต์เพิ่งเปิด/คำค้นเปลี่ยน
 * @param {string} q  คำค้นปัจจุบัน ('' = เปิดลิสต์เฉยๆ ยังไม่พิมพ์)
 * @returns {number} 0 = แถวแรกของผลค้นหา · NO_ROW = ไม่เล็งอะไร
 */
export function initialActiveRow(q) {
  return String(q ?? '').trim() === '' ? NO_ROW : 0;
}

/**
 * แถวถัดไปเมื่อกดลูกศร — เริ่มจาก NO_ROW แล้วกดลง ต้องได้แถวแรก
 * @param {number} active  แถวที่เล็งอยู่
 * @param {1|-1} dir       1 = ลง · -1 = ขึ้น
 * @param {number} len     จำนวนแถวที่แสดงอยู่
 */
export function moveActiveRow(active, dir, len) {
  if (!(len > 0)) return NO_ROW;
  const a = Number.isInteger(active) ? active : NO_ROW;
  if (dir > 0) return Math.min(a + 1, len - 1);
  return Math.max(a - 1, 0);
}
