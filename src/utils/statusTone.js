/* ── ตารางสี/ป้าย — นิยามจริงอยู่ที่นี่ที่เดียว ─────────────────────────────────────── */
export const STATUS_COLOR = { good: '#22c55e', warn: '#f59e0b', bad: '#ef4444', none: '#64748b' };
export const STATUS_LABEL = { good: 'ตามเป้า', warn: 'เฉียดเป้า', bad: 'หลุดเป้า', none: 'ตัดสินไม่ได้' };
export const statusColor = (s) => STATUS_COLOR[s] || STATUS_COLOR.none;
export const statusLabel = (s) => STATUS_LABEL[s] || STATUS_LABEL.none;

/**
 * สถานะเทียบเป้า
 * @param better ทิศทางที่ดี: `'up'` (ยิ่งมากยิ่งดี เช่น OEE) · `'down'` (ยิ่งน้อยยิ่งดี เช่น ของเสีย)
 * เกณฑ์เหลือง = พลาดเป้าไม่เกิน 5% ของค่าเป้า — เลือกให้ตรงกับไฟเหลืองของ Andon ในระบบ
 * ⚠️ เป้า 0 (เช่น "อุบัติเหตุ 0 ครั้ง") ไม่มีแถบเหลือง — เกิน 0 คือแดงทันที ไม่มีครึ่งทาง
 * 🔴 ไม่มีค่า **หรือ** ไม่มีเป้า ⇒ `'none'` เสมอ (กฎข้อ 2 ด้านบน)
 */
export function statusOf(value, target, better = 'up') {
  if (value == null || Number.isNaN(Number(value))) return 'none';
  if (target == null || Number.isNaN(Number(target))) return 'none';
  const v = Number(value), t = Number(target);
  if (better === 'down') {
    if (t === 0) return v === 0 ? 'good' : 'bad';
    if (v <= t) return 'good';
    return v <= t * 1.05 ? 'warn' : 'bad';
  }
  if (v >= t) return 'good';
  return v >= t * 0.95 ? 'warn' : 'bad';
}

/**
 * สีของ "ตัวเลขบนการ์ด KPI" — ตัวช่วยที่หน้าทั่วไปควรเรียก แทนการเลือกสีเอง
 *
 * ใช้ 3 แบบ:
 *   · มีเป้า → `toneOf({ value, target, better })`            ⇒ เขียว/เหลือง/แดง ตามผลจริง
 *   · เป็น "ตัวนับสิ่งที่ค้าง" ที่ 0 = ดี → `toneOf({ value, zeroIsGood: true })`
 *     (เป้าโดยปริยายคือ 0 จึงถือว่ามีเป้า) · `over` = สีตอนไม่เป็นศูนย์ **เลือกตามผลที่เกิดจริง**:
 *       `'bad'` (ค่าเริ่มต้น) = ของกำลังพัง/ผลิตหยุดอยู่ เช่น **Downtime ค้าง**
 *       `'warn'` = เรื่องที่ต้องไปจัดการแต่สายการผลิตยังเดิน เช่น **4M รออนุมัติ · ใบซ่อมค้าง**
 *       ⚠️ อย่าใส่ `'bad'` ให้ทุกคิวที่ยังไม่ว่าง — จอที่แดงตลอดเวลาคือจอที่คนเลิกมอง
 *   · นอกนั้นทั้งหมด → **เทา** เพราะตัดสินไม่ได้ (ห้ามใส่สีให้สวย)
 *
 * @returns `'good' | 'warn' | 'bad' | 'none'`
 */
export function toneOf({ value, target = null, better = 'up', zeroIsGood = false, over = 'bad' } = {}) {
  if (zeroIsGood) {
    const t = statusOf(value, 0, 'down');
    return t === 'bad' ? over : t;
  }
  return statusOf(value, target, better);
}

/**
 * สีตัวหนังสือของตัวเลขบนการ์ด — เทาของ "ตัดสินไม่ได้" ต้องอ่านออกบนจอ TV
 * ⇒ คืน token ของธีม (`--text`) แทนเทาจางๆ เมื่อสถานะเป็น `none`
 *   (เทา `#64748b` ใช้กับ *ไฟ/จุดสถานะ* ได้ แต่ถ้าเอาไปทาตัวเลขใหญ่จะจมพื้นดำบนจอ 43 นิ้ว)
 */
export const toneInk = (s) => (s === 'none' ? 'var(--text)' : statusColor(s));

/** มี "เป้า" ให้เทียบจริงไหม — จอควรเขียนกำกับเมื่อไม่มี (ห้ามเงียบแล้วปล่อยให้เดาว่าเขียว = ดี) */
export const hasTarget = (target) => target != null && !Number.isNaN(Number(target));
