/** ยอดที่ทำได้จริงของใบ ณ ตอนปิดกะ — ค่าที่คนกรอกในหน้าปิดกะชนะ `qty_actual` ที่บันทึกไว้
 *  🔴 ช่องว่าง/ค่าพัง = ถอยไป `qty_actual` **ไม่ใช่ 0** (0 = "ยังไม่แตะ" ซึ่งคนละความหมาย) */
export function closeQtyOf(order, qtyInput) {
  const raw = qtyInput?.[order?.id];
  const typed = raw === '' || raw == null ? null : parseInt(raw, 10);
  if (typed != null && Number.isFinite(typed) && typed >= 0) return typed;
  return Number(order?.qty_actual) || 0;
}

/**
 * แยกใบที่ยังไม่ปิด ออกเป็น 2 กอง
 * @param {Array}  orders    ใบสถานะ `open` ของกะนี้
 * @param {Object} qtyInput  map id → ยอดที่คนกรอกในหน้าปิดกะ (string ได้)
 * @returns {{ autoCarry: Array, needDecision: Array }}
 *   · `autoCarry`    = ยังไม่แตะเลย ⇒ ระบบยกให้เอง
 *   · `needDecision` = แตะแล้ว ⇒ คนต้องตัดสิน
 */
export function splitCloseOrders(orders = [], qtyInput = {}) {
  const autoCarry = [], needDecision = [];
  for (const o of orders || []) {
    if (!o) continue;
    (closeQtyOf(o, qtyInput) > 0 ? needDecision : autoCarry).push(o);
  }
  return { autoCarry, needDecision };
}

/** payload ของใบที่ยกอัตโนมัติ — ยอดที่ทำได้ = 0 เสมอ (นิยามของกองนี้)
 *  🔴 **ห้ามเซ็ต `carry_over_from_session_id`** — ช่องนั้นแปลว่า "ใบนี้ถูกรับ*มา*จากกะก่อน"
 *     ใส่ตรงนี้ = ใบชี้กลับมาหาตัวเอง แล้วจอขึ้นป้าย "ยกยอดมา" ผิด (กับดักเดิมในหน้าปิดกะ) */
export function autoCarryPatch(order, { shiftLabel = '', dateLabel = '', stoppedAt = null } = {}) {
  return {
    status: 'carry_over',
    qty_actual: 0,
    stopped_at: stoppedAt,
    carry_over_note: `ยกอัตโนมัติ: ยังไม่ได้ผลิต 0/${Number(order?.qty) || 0} ชิ้น`
      + `${shiftLabel || dateLabel ? ` จาก${shiftLabel}${dateLabel ? ` ${dateLabel}` : ''}` : ''}`,
  };
}

/** ข้อความบนจอปิดกะ — ต้องบอกให้ชัดว่าระบบกำลังจะทำอะไรให้ (ห้ามยกเงียบ) */
export function autoCarryText(n, pcs) {
  if (!n) return null;
  return `🔁 อีก ${n} ใบยังไม่ได้ผลิตเลย (${Number(pcs || 0).toLocaleString()} ชิ้น) — ระบบจะ`
    + `ยกยอดต่อให้อัตโนมัติ ไม่ต้องกดทีละใบ`;
}
