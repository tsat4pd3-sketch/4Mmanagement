def say(s, th):
    s.notes_slide.notes_text_frame.text = th
    narration.append(th)


def content(title, sub=None, tag=None):
    s = T.blank(p); page[0] += 1
    T.head(s, title, sub)
    if tag:
        T.rect(s, 11.0, 0.36, 2.05, 0.4, fill=ORANGE, shape=MSO_SHAPE.ROUNDED_RECTANGLE)
