def flow(s, x, y, label, steps, old=True, w_total=12.4):
    T.rect(s, x, y, 0.9, 0.5, fill=GREY if old else GREEN_D)
    T.text(s, x, y, 0.9, 0.5, [[(label, {"sz": 14, "b": True, "c": WHITE})]], align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)
    n = len(steps); gap = 0.08
    cw = (w_total - 1.0 - gap * (n - 1)) / n
    for i, t in enumerate(steps):
        cx = x + 1.0 + i * (cw + gap)
        sh = s.shapes.add_shape(MSO_SHAPE.CHEVRON if i else MSO_SHAPE.PENTAGON, Inches(cx), Inches(y), Inches(cw + 0.15), Inches(0.5))
        sh.fill.solid(); sh.fill.fore_color.rgb = (RGB_OLD if old else (GREEN if i % 2 == 0 else GREEN_D)); sh.line.fill.background()
        T.text(s, cx + 0.18, y, cw - 0.15, 0.5, [[(t, {"sz": T.fit_one_line(t, cw - 0.2, 12, 9), "b": True, "c": GREY if old else WHITE})]], align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)


